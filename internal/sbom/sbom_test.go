// ─── Document generation ──────────────────────────────────────────────────────

func TestGenerateDocument_StructureAndFields(t *testing.T) {
	comps := []sbom.Component{
		{Ecosystem: sbom.EcosystemGo, Name: "github.com/foo/bar", Version: "v1.0.0",
			PURL: sbom.BuildPURL(sbom.EcosystemGo, "github.com/foo/bar", "v1.0.0"),
			SPDXID: sbom.BuildSPDXID(sbom.EcosystemGo, "github.com/foo/bar", "v1.0.0")},
		{Ecosystem: sbom.EcosystemCargo, Name: "serde", Version: "1.0.210",
			PURL: sbom.BuildPURL(sbom.EcosystemCargo, "serde", "1.0.210"),
			SPDXID: sbom.BuildSPDXID(sbom.EcosystemCargo, "serde", "1.0.210"),
			Checksum: "abcdef"},
	}
	ctx := sbom.BuildContext{
		GeneratedAt:    time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC),
		ToolVersion:    "v1.2.3",
		ReleaseVersion: "v1.2.3",
		Commit:         "deadbeef",
	}
	doc := sbom.GenerateDocument(comps, ctx)

	if doc.SPDXVersion != "SPDX-2.3" {
		t.Errorf("SPDXVersion = %q, want SPDX-2.3", doc.SPDXVersion)
	}
	if doc.DataLicense != "CC0-1.0" {
		t.Errorf("DataLicense = %q, want CC0-1.0", doc.DataLicense)
	}
	if doc.SPDXID != "SPDXRef-DOCUMENT" {
		t.Errorf("SPDXID = %q, want SPDXRef-DOCUMENT", doc.SPDXID)
	}
	// Packages = root package + 2 dependencies.
	if len(doc.Packages) != 3 {
		t.Errorf("len(Packages) = %d, want 3", len(doc.Packages))
	}
	if doc.DocumentHash == "" {
		t.Error("DocumentHash is empty; must be computed")
	}
}

func TestGenerateDocument_Deterministic(t *testing.T) {
	comps := []sbom.Component{
		{Ecosystem: sbom.EcosystemGo, Name: "github.com/a/b", Version: "v1.0.0",
			PURL: sbom.BuildPURL(sbom.EcosystemGo, "github.com/a/b", "v1.0.0"),
			SPDXID: sbom.BuildSPDXID(sbom.EcosystemGo, "github.com/a/b", "v1.0.0")},
		{Ecosystem: sbom.EcosystemCargo, Name: "tokio", Version: "1.0.0",
			PURL: sbom.BuildPURL(sbom.EcosystemCargo, "tokio", "1.0.0"),
			SPDXID: sbom.BuildSPDXID(sbom.EcosystemCargo, "tokio", "1.0.0")},
	}
	ctx := sbom.BuildContext{
		GeneratedAt: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC),
		ReleaseVersion: "v1.0.0",
		Commit: "aaaa",
	}
	doc1 := sbom.GenerateDocument(comps, ctx)
	doc2 := sbom.GenerateDocument(comps, ctx)
	if doc1.DocumentHash != doc2.DocumentHash {
		t.Errorf("DocumentHash not deterministic: %q vs %q", doc1.DocumentHash, doc2.DocumentHash)
	}
}

func TestGenerateDocument_DeduplicatesComponents(t *testing.T) {
	// Same SPDXID from two different inputs (e.g. duplicate transitive dep).
	id := sbom.BuildSPDXID(sbom.EcosystemGo, "github.com/foo/bar", "v1.0.0")
	comps := []sbom.Component{
		{Ecosystem: sbom.EcosystemGo, Name: "github.com/foo/bar", Version: "v1.0.0",
			PURL: sbom.BuildPURL(sbom.EcosystemGo, "github.com/foo/bar", "v1.0.0"), SPDXID: id},
		{Ecosystem: sbom.EcosystemGo, Name: "github.com/foo/bar", Version: "v1.0.0",
			PURL: sbom.BuildPURL(sbom.EcosystemGo, "github.com/foo/bar", "v1.0.0"), SPDXID: id},
	}
	doc := sbom.GenerateDocument(comps, sbom.BuildContext{ReleaseVersion: "v1.0.0"})
	// Packages = 1 root + 1 deduplicated dep.
	if len(doc.Packages) != 2 {
		t.Errorf("len(Packages) = %d after dedup, want 2", len(doc.Packages))
	}
}

