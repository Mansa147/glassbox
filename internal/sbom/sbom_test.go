// ─── Cargo.lock parser ────────────────────────────────────────────────────────

const sampleCargoLock = `
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "serde"
version = "1.0.210"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "sha256:abcdef1234567890abcdef1234567890abcdef1234567890abcdef1234567890"

[[package]]
name = "serde_json"
version = "1.0.128"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "sha256:1234567890abcdef1234567890abcdef1234567890abcdef1234567890abcdef"

[[package]]
name = "simulator"
version = "0.1.0"
`

func TestParseCargoLock_Basic(t *testing.T) {
	comps, err := sbom.ParseCargoLock(strings.NewReader(sampleCargoLock))
	if err != nil {
		t.Fatalf("ParseCargoLock: %v", err)
	}
	// "simulator" has no source → local workspace member, must be excluded.
	if len(comps) != 2 {
		t.Fatalf("len(comps) = %d, want 2 (local member excluded)", len(comps))
	}
	for _, c := range comps {
		if c.Ecosystem != sbom.EcosystemCargo {
			t.Errorf("component %q: Ecosystem = %q, want cargo", c.Name, c.Ecosystem)
		}
		if c.PURL == "" {
			t.Errorf("component %q: PURL is empty", c.Name)
		}
		if c.Checksum == "" {
			t.Errorf("component %q: Checksum is empty (should be stripped of sha256: prefix)", c.Name)
		}
		// Checksum must not contain the "sha256:" prefix.
		if strings.Contains(c.Checksum, "sha256:") {
			t.Errorf("component %q: Checksum still contains prefix: %q", c.Name, c.Checksum)
		}
	}
}

