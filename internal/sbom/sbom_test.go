// ─── Component / PURL / SPDXID ───────────────────────────────────────────────

func TestBuildPURL(t *testing.T) {
	cases := []struct {
		eco     sbom.Ecosystem
		name    string
		version string
		want    string
	}{
		{sbom.EcosystemGo, "github.com/foo/bar", "v1.2.3", "pkg:golang/github.com/foo/bar@v1.2.3"},
		{sbom.EcosystemCargo, "serde", "1.0.0", "pkg:cargo/serde@1.0.0"},
		{sbom.EcosystemNPM, "@stellar/stellar-sdk", "14.5.0", "pkg:npm/@stellar/stellar-sdk@14.5.0"},
	}
	for _, c := range cases {
		got := sbom.BuildPURL(c.eco, c.name, c.version)
		if got != c.want {
			t.Errorf("BuildPURL(%q,%q,%q) = %q, want %q", c.eco, c.name, c.version, got, c.want)
		}
	}
}

func TestBuildSPDXID_ContainsNoInvalidChars(t *testing.T) {
	id := sbom.BuildSPDXID(sbom.EcosystemGo, "github.com/foo/bar", "v1.2.3")
	if !strings.HasPrefix(id, "SPDXRef-") {
		t.Errorf("SPDXID %q must start with SPDXRef-", id)
	}
	// SPDX IDs may only contain letters, digits, "." and "-".
	for _, c := range id {
		if !((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
			(c >= '0' && c <= '9') || c == '.' || c == '-') {
			t.Errorf("SPDXID %q contains invalid character %q", id, c)
		}
	}
}

// ─── Go module parser ─────────────────────────────────────────────────────────

func TestParseGoModules_Basic(t *testing.T) {
	input := `
{"Path":"github.com/foo/bar","Version":"v1.2.3","Main":false}
{"Path":"github.com/baz/qux","Version":"v0.1.0","Main":false}
{"Path":"github.com/dotandev/glassbox","Version":"","Main":true}
`
	comps, err := sbom.ParseGoModules(strings.NewReader(input))
	if err != nil {
		t.Fatalf("ParseGoModules: %v", err)
	}
	if len(comps) != 2 {
		t.Fatalf("len(comps) = %d, want 2 (main module excluded)", len(comps))
	}
	names := map[string]bool{}
	for _, c := range comps {
		names[c.Name] = true
		if c.Ecosystem != sbom.EcosystemGo {
			t.Errorf("component %q: Ecosystem = %q, want go", c.Name, c.Ecosystem)
		}
		if c.PURL == "" {
			t.Errorf("component %q: PURL is empty", c.Name)
		}
		if c.SPDXID == "" {
			t.Errorf("component %q: SPDXID is empty", c.Name)
		}
	}
	if !names["github.com/foo/bar"] || !names["github.com/baz/qux"] {
		t.Errorf("missing expected component; got %v", names)
	}
}

