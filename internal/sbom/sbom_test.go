// ─── Marshal / JSON round-trip ────────────────────────────────────────────────

func TestMarshal_ValidJSON(t *testing.T) {
	doc := sbom.GenerateDocument([]sbom.Component{
		{Ecosystem: sbom.EcosystemNPM, Name: "chalk", Version: "4.1.2",
			PURL: sbom.BuildPURL(sbom.EcosystemNPM, "chalk", "4.1.2"),
			SPDXID: sbom.BuildSPDXID(sbom.EcosystemNPM, "chalk", "4.1.2")},
	}, sbom.BuildContext{ReleaseVersion: "v1.0.0"})

	data, err := sbom.Marshal(doc)
	if err != nil {
		t.Fatalf("Marshal: %v", err)
	}
	// Must be valid JSON.
	var roundTrip sbom.SPDXDocument
	if err := json.Unmarshal(data, &roundTrip); err != nil {
		t.Fatalf("round-trip JSON unmarshal failed: %v", err)
	}
	if roundTrip.SPDXVersion != "SPDX-2.3" {
		t.Errorf("round-trip SPDXVersion = %q, want SPDX-2.3", roundTrip.SPDXVersion)
	}
}

