func TestGenerateFromFiles_InlineGoModules(t *testing.T) {
	// Pass inline JSON via GoModulesJSON (starts with '{').
	goJSON := `{"Path":"github.com/foo/bar","Version":"v1.0.0","Main":false}`
	result, err := sbom.GenerateFromFiles(sbom.GenerateOptions{
		GoModulesJSON: goJSON,
		Context: sbom.BuildContext{ReleaseVersion: "v1.0.0"},
	})
	if err != nil {
		t.Fatalf("GenerateFromFiles: %v", err)
	}
	if result.Document == nil {
		t.Fatal("Document is nil")
	}
	if result.ComponentCounts[sbom.EcosystemGo] != 1 {
		t.Errorf("Go component count = %d, want 1", result.ComponentCounts[sbom.EcosystemGo])
	}
}

func TestGenerateFromFiles_MissingOptionalFileIsWarning(t *testing.T) {
	// A non-existent Cargo.lock should produce a warning, not a hard error,
	// as long as at least one source (inline Go JSON) succeeds.
	goJSON := `{"Path":"github.com/foo/bar","Version":"v1.0.0","Main":false}`
	result, err := sbom.GenerateFromFiles(sbom.GenerateOptions{
		GoModulesJSON: goJSON,
		CargoLockPath: "/nonexistent/path/Cargo.lock",
		Context:       sbom.BuildContext{ReleaseVersion: "v1.0.0"},
	})
	if err != nil {
		t.Fatalf("missing optional file should not fail: %v", err)
	}
	if len(result.Warnings) == 0 {
		t.Error("expected at least one warning for missing Cargo.lock")
	}
}

func TestGenerateFromFiles_VersionMatchesLockfile(t *testing.T) {
	// Components from the lockfile must have exact version strings matching
	// what was in the input — no normalisation should alter them.
	goJSON := `{"Path":"github.com/stretchr/testify","Version":"v1.11.1","Main":false}`
	result, err := sbom.GenerateFromFiles(sbom.GenerateOptions{
		GoModulesJSON: goJSON,
		Context:       sbom.BuildContext{ReleaseVersion: "v0.1.0"},
	})
	if err != nil {
		t.Fatalf("GenerateFromFiles: %v", err)
	}
	found := false
	for _, pkg := range result.Document.Packages {
		if pkg.Name == "github.com/stretchr/testify" {
			if pkg.Version != "v1.11.1" {
				t.Errorf("version = %q, want v1.11.1 (must match lockfile exactly)", pkg.Version)
			}
			found = true
		}
	}
	if !found {
		t.Error("github.com/stretchr/testify not found in generated document")
	}
}
